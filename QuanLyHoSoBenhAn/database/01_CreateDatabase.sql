CREATE OR ALTER TRIGGER dbo.TR_PHIEUKHAM_RequirePaymentOnComplete
ON dbo.PHIEUKHAM
AFTER UPDATE
AS
BEGIN
    SET NOCOUNT ON;
    IF EXISTS(
        SELECT 1
        FROM inserted i
        JOIN deleted d ON d.MaPhieuKham=i.MaPhieuKham
        WHERE i.TrangThai=N'Hoàn tất'
          AND ISNULL(d.TrangThai,N'')<>N'Hoàn tất'
          AND NOT EXISTS(
              SELECT 1 FROM dbo.THANHTOANVIENPHI t
              WHERE t.MaPhieuKham=i.MaPhieuKham
                AND t.TrangThai=N'Đã thanh toán'
          )
    )
    BEGIN
        THROW 50003, N'Không thể hoàn tất phiếu khám khi chưa thanh toán viện phí.', 1;
    END
END;
GO

CREATE OR ALTER PROCEDURE dbo.sp_DangKyLanDau
    @HoTen NVARCHAR(150), @DiaChi NVARCHAR(255), @NgaySinh DATE,
    @DienThoai VARCHAR(20), @Anh3x4 NVARCHAR(300)=NULL, @SoTienLePhi DECIMAL(18,2)
AS
BEGIN
    SET NOCOUNT ON; SET XACT_ABORT ON;
    BEGIN TRY
        BEGIN TRAN;
        INSERT dbo.BENHNHAN(HoTen,DiaChi,NgaySinh,DienThoai,Anh3x4)
        VALUES(@HoTen,@DiaChi,@NgaySinh,@DienThoai,@Anh3x4);
        DECLARE @MaBenhNhan INT=SCOPE_IDENTITY();
        INSERT dbo.PHIEUDANGKY(MaBenhNhan) VALUES(@MaBenhNhan);
        INSERT dbo.LEPHINAM(MaBenhNhan,NamApDung,SoTien)
        VALUES(@MaBenhNhan,YEAR(GETDATE()),@SoTienLePhi);
        INSERT dbo.HOSOBENHAN(MaBenhNhan) VALUES(@MaBenhNhan);
        DECLARE @MaHoSo INT=SCOPE_IDENTITY();
        COMMIT;
        SELECT @MaBenhNhan MaBenhNhan,@MaHoSo MaHoSo,
               (SELECT MaHoSoCode FROM dbo.HOSOBENHAN WHERE MaHoSo=@MaHoSo) MaHoSoCode;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT>0 ROLLBACK;
        THROW;
    END CATCH
END;
GO

CREATE OR ALTER PROCEDURE dbo.sp_ThanhToanVaHoanTatPhieuKham
    @MaPhieuKham INT, @SoTien DECIMAL(18,2), @GhiChu NVARCHAR(500)=NULL
AS
BEGIN
    SET NOCOUNT ON; SET XACT_ABORT ON;
    BEGIN TRY
        BEGIN TRAN;
        IF NOT EXISTS(SELECT 1 FROM dbo.PHIEUKHAM WHERE MaPhieuKham=@MaPhieuKham)
            THROW 50001, N'Phiếu khám không tồn tại.', 1;
        IF EXISTS(SELECT 1 FROM dbo.THANHTOANVIENPHI WHERE MaPhieuKham=@MaPhieuKham)
            THROW 50002, N'Phiếu khám đã có thanh toán.', 1;
        INSERT dbo.THANHTOANVIENPHI(MaPhieuKham,SoTien,GhiChu)
        VALUES(@MaPhieuKham,@SoTien,@GhiChu);
        UPDATE dbo.PHIEUKHAM
        SET TrangThai=N'Hoàn tất',NgayXuatVien=SYSDATETIME()
        WHERE MaPhieuKham=@MaPhieuKham;
        COMMIT;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT>0 ROLLBACK;
        THROW;
    END CATCH
END;
GO
