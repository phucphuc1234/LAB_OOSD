const router = require('express').Router();
const authenticate = require('../middlewares/authMiddleware');
const authorize = require('../middlewares/roleMiddleware');
const { action } = require('../utils/http');
const service = require('../services/facilityService');
const admin = authorize('Quản trị viên');
const medical = authorize('Nhân viên', 'Quản trị viên');
router.use(authenticate);
router.get('/areas', action(req => service.getAreas(req.user, req.query)));
router.post('/areas', admin, action(req => service.saveArea(req.user, null, req.body), 'Đã thêm khu vực trong TP. Hồ Chí Minh.', 201));
router.put('/areas/:id', admin, action(req => service.saveArea(req.user, req.params.id, req.body), 'Đã lưu khu vực.'));
router.get('/assignments', admin, action(() => service.getAssignments()));
router.put('/assignments/:accountId', admin, action(req => service.assignFacilities(req.user, req.params.accountId, req.body), 'Đã cập nhật phạm vi cơ sở của nhân viên.'));
router.get('/', action(req => service.getFacilities(req.user, req.query)));
router.post('/', admin, action(req => service.saveFacility(req.user, null, req.body), 'Đã thêm cơ sở tiêm.', 201));
router.put('/:id', admin, action(req => service.saveFacility(req.user, req.params.id, req.body), 'Đã lưu cơ sở tiêm.'));
router.get('/:id/vaccines', medical, action(req => service.getFacilityVaccines(req.user, req.params.id)));
router.put('/:id/vaccines/:vaccineId', medical, action(req => service.setFacilityVaccine(req.user, req.params.id, req.params.vaccineId, req.body), 'Đã cập nhật vaccine tại cơ sở.'));
module.exports = router;
